// Builds dist/: an allowlisted copy of site/ plus one generated module carrying content and data.
import fs from 'node:fs';
import path from 'node:path';
import { root, loadContent, loadDatasets, entityRecords } from './lib.mjs';
import { runtimeFiles } from './files.mjs';

export { runtimeFiles };
const dist = path.join(root, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
for (const f of runtimeFiles) {
  if (f === 'bundle.js') continue;
  const src = path.join(root, 'site', f);
  if (!fs.existsSync(src)) throw new Error('missing runtime file ' + f);
  fs.mkdirSync(path.dirname(path.join(dist, f)), { recursive: true });
  fs.copyFileSync(src, path.join(dist, f));
}
const content = loadContent(), datasets = loadDatasets(content);
// DATASETS is keyed by case id; DATA stays the first case's dataset for anything that reads the earlier shape.
// ENTITIES is the whole station directory as flat graph.* records; the app scopes it to each case's window.
const bundle = `// generated by tools/build.mjs\nexport const CONTENT = ${JSON.stringify(content)};\nexport const DATASETS = ${JSON.stringify(datasets)};\nexport const DATA = DATASETS[${JSON.stringify(content.cases[0].id)}];\nexport const ENTITIES = ${JSON.stringify(entityRecords(content.entities))};\n`;
fs.writeFileSync(path.join(dist, 'bundle.js'), bundle);
console.log('built dist/', runtimeFiles.length, 'files;', Object.values(datasets).map(d => d.events.length).join(' + '), 'events');
