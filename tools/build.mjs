// Builds dist/: an allowlisted copy of site/ plus one generated module carrying content and data.
import fs from 'node:fs';
import path from 'node:path';
import { root, loadContent, loadData } from './lib.mjs';
import { runtimeFiles } from './files.mjs';

export { runtimeFiles };
const dist = path.join(root, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
for (const f of runtimeFiles) {
  if (f === 'bundle.js') continue;
  const src = path.join(root, 'site', f);
  if (!fs.existsSync(src)) throw new Error('missing runtime file ' + f);
  fs.mkdirSync(path.dirname(path.join(dist, f)), { recursive: true });
  fs.copyFileSync(src, path.join(dist, f));
}
const content = loadContent(), data = loadData();
const bundle = `// generated by tools/build.mjs\nexport const CONTENT = ${JSON.stringify(content)};\nexport const DATA = ${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(dist, 'bundle.js'), bundle);
console.log('built dist/', runtimeFiles.length, 'files;', data.events.length, 'events');
